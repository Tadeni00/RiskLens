    @classmethod
    def svg(
        cls,
        icon_name: str,
        size: int = 16,
        color: str = "currentColor",
        stroke_width: float = 2,
        class_name: str = "",
    ) -> str:
        """Render an SVG icon."""
        paths = getattr(cls, icon_name.upper(), None)
        if not paths:
            return ""
        cls_attr = f' class="{class_name}"' if class_name else ""
        return (
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
            f'viewBox="0 0 24 24" fill="none" stroke="{color}" '
            f'stroke-width="{stroke_width}" stroke-linecap="round" '
            f'stroke-linejoin="round"{cls_attr}>{paths}</svg>'
        )

    @classmethod
    def html(
        cls,
        icon_name: str,
        size: int = 16,
        color: str = "currentColor",
        stroke_width: float = 2,
        class_name: str = "",
        vertical_align: str = "middle",
    ) -> str:
        """Render an SVG icon wrapped for inline HTML use."""
        svg = cls.svg(icon_name, size, color, stroke_width, class_name)
        return f'<span style="display:inline-flex;align-items:center;vertical-align:{vertical_align};line-height:1">{svg}</span>'
